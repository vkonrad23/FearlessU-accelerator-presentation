export function AIArchitecture() {
  const { t } = useLanguage();
  const mode = useJourneyStore((state) => state.researchMode);
  const validationEvent = useJourneyStore((state) => state.validationEvent);
  const setResearchMode = useJourneyStore((state) => state.setResearchMode);
  const activeMode = modes.find((item) => item.id === mode) ?? modes[0]!;
  const selectMode = (next: ResearchMode) => {
    if (next === 'validation') {
      if (validationEvent) useJourneyStore.setState({ researchMode: 'validation' });
      return;
    }
    setResearchMode(next);
  };

  return (
    <section id="ai-architecture" className={`${styles.section} page-width`} data-camera-stop="0.31" aria-labelledby="architecture-title">
      <div className={styles.panel}>
        <header className={styles.header}>
          <div>
            <p className={styles.eyebrow}><span aria-hidden="true" />{t('RESEARCH ENGINE · LONG-TERM VISION')}</p>
            <h2 id="architecture-title" className={styles.title}>{t('Beyond Existing CBT.')}<br /><em>{t('Toward new discoveries.')}</em></h2>
          </div>
          <p className={styles.description}>{t('AI could help researchers connect psychological literature, propose questions, and structure ideas for expert-led evaluation. This platform is a research direction; those capabilities are not implemented in the current prototype.')}</p>
        </header>

        <div className={styles.modePanel}>
          <div className={styles.modeHeader}>
            <div><span className={styles.corePulse} aria-hidden="true" /><div><strong>{t('Holographic core')}</strong><small>{t('Illustrative state control')}</small></div></div>
            <span className={styles.visualOnly}><CircleDot size={13} aria-hidden="true" />{t('Visual concept only')}</span>
          </div>
          <div className={styles.modeBody}>
            <div className={styles.modeControls}>
              <div className={styles.modeButtons} role="group" aria-label={t('Research engine visual states')}>
                {modes.map((item) => {
                  const unavailable = item.id === 'validation' && !validationEvent;
                  return (
                    <button
                      key={item.id}
                      type="button"
                      className={styles.modeButton}
                      data-mode={item.id}
                      aria-pressed={mode === item.id}
                      disabled={unavailable}
                      title={unavailable ? t('Available only after the application supplies a completed validation event.') : undefined}
                      onClick={() => selectMode(item.id)}
                    >
                      {item.label === 'RESEARCH' && <Network size={14} aria-hidden="true" />}
                      {item.label === 'HYPOTHESIS GENERATION' && <Waypoints size={14} aria-hidden="true" />}
                      {item.label === 'EVALUATION' && <Microscope size={14} aria-hidden="true" />}
                      {item.label === 'VALIDATION' && <Check size={14} aria-hidden="true" />}
                      {t(item.label)}
                    </button>
                  );
                })}
              </div>
              <p className={styles.modeDescription} role="status" aria-live="polite">{t(activeMode.description)}</p>
              {validationEvent ? (
                <p className={styles.validationEvent}><Check size={15} aria-hidden="true" />{t('Application-provided validation event: {study} · {date}').replace('{study}', validationEvent.studyId).replace('{date}', validationEvent.validatedAt)}</p>
              ) : (
                <p className={styles.validationPending}><LockKeyhole size={14} aria-hidden="true" />{t('No validation event has been supplied by the application.')}</p>
              )}
            </div>
            <ResearchCorePreview mode={mode} validated={Boolean(validationEvent && mode === 'validation')} caption={t('CORE · VISUAL ONLY')} />
          </div>
        </div>

        <div className={styles.workflowHeading}>
          <div><p className={styles.eyebrow}><span aria-hidden="true" />{t('PROPOSED RESEARCH FLOW')}</p><h3>{t('From literature to reviewed evidence.')}</h3></div>
          <p>{t('Choose a stage to change the core’s visual state. The workflow itself does not run.')}</p>
        </div>

        <ol className={styles.workflow} aria-label={t('Illustrative research workflow')}>
          {workflow.map((stage, index) => {
            const Icon = stage.icon;
            const unavailable = stage.mode === 'validation' && !validationEvent;
            const active = mode === stage.mode && !unavailable;
            return (
              <li key={stage.title} className={styles.workflowItem} data-active={active}>
                <button type="button" className={styles.workflowButton} aria-pressed={active} disabled={unavailable} onClick={() => selectMode(stage.mode)}>
                  <span className={styles.workflowTop}><span className={styles.workflowIcon}><Icon size={17} strokeWidth={1.5} aria-hidden="true" /></span><span className={styles.workflowNumber}>0{index + 1}</span></span>
                  <span className={styles.workflowTitle}>{t(stage.title)}</span>
                  <span className={styles.workflowDetail}>{t(stage.detail)}</span>
                  <span className={styles.workflowStatus}>{unavailable ? <LockKeyhole size={12} aria-hidden="true" /> : <CircleDot size={12} aria-hidden="true" />}{unavailable ? t('Awaiting an application event') : t('Research vision · not implemented')}</span>
                </button>
                {index < workflow.length - 1 && <ArrowRight className={styles.workflowConnector} size={14} aria-hidden="true" />}
              </li>
            );
          })}
        </ol>

        <aside className={styles.boundary}>
          <LockKeyhole size={17} aria-hidden="true" />
          <p><strong>{t('Today: an educational CBT-informed demo using local rules.')}</strong> {t('There is no live literature retrieval, hypothesis generation, expert review, or clinical validation in this website. The research engine and its states are visual representations of a future direction, not evidence of completed research.')}</p>
        </aside>
        <a className={styles.link} href="#validation-plan">{t('See the proposed validation plan')} <ArrowDown size={15} aria-hidden="true" /></a>
      </div>
    </section>
  );
}
